"""Generates src/data/indbFoods.ts from the Indian Nutrient Databank (INDB).

INDB (Vijayakumar et al. 2024, https://github.com/lindsayjaacks/Indian-Nutrient-Databank-INDB-)
has ~1,000 Indian recipes, but some values are clearly wrong (deep-fried items count all the
frying oil, some "servings" are a whole jar). We drop entries that fail sanity checks and mark
the rest as approximate in the app. Our hand-checked list in foods.ts always takes priority.

    .venv/bin/python build_indb_foods.py
"""

import json
import re
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
INDB = Path(__file__).resolve().parent / 'data/nutrition/indb/INDB.xlsx'
OUT = ROOT / 'src/data/indbFoods.ts'

WHOLE_RECIPE_UNITS = {'jar', 'dish', 'souffle dish', 'cake', 'loaf', 'pie', 'tray', 'pizza', 'bottle'}
SMALL_UNITS = {'piece', 'ladoo', 'burfi', 'biscuit', 'cookie', 'vada', 'poori', 'cutlet', 'triangle',
               'idli', 'samosa', 'kachori', 'pakora', 'tikki', 'kebab', 'roll', 'muffin'}


def rejection_reason(r) -> str | None:
    name, unit = r.food_name.lower(), str(r.servings_unit).lower()
    kcal, p, c, f = r.unit_serving_energy_kcal, r.unit_serving_protein_g, r.unit_serving_carb_g, r.unit_serving_fat_g
    if any(pd.isna(v) for v in (kcal, p, c, f)) or kcal <= 0:
        return 'missing values'
    if unit in WHOLE_RECIPE_UNITS:
        return 'serving is a whole recipe'
    if 'powder' in name and 'milk powder' not in name or re.search(r'\b(garam|chat|kashmiri) masala$', name):
        return 'spice mix'
    if kcal > 900:
        return 'over 900 kcal per serving'
    if f * 9 / kcal > 0.7 and kcal > 200:
        return 'frying oil counted as eaten'
    if unit in SMALL_UNITS and kcal > 300:
        return 'too high for one piece'
    if abs(4 * p + 4 * c + 9 * f - kcal) / kcal > 0.35:
        return 'calories do not match macros'
    return None


def split_name(food_name: str) -> tuple[str, list[str]]:
    """'Curd rice (Dahi bhaat/Dahi chawal/Thayir saadam)' -> ('Curd rice', ['Dahi bhaat', ...])."""
    aliases = []
    for group in re.findall(r'\(([^)]*)\)?', food_name):
        aliases += [a.strip() for a in re.split(r'[/,]', group) if a.strip()]
    name = re.sub(r'\s*\([^)]*\)?', '', food_name).strip() or food_name.strip()
    return name, aliases


def curated_names() -> set[str]:
    src = (ROOT / 'src/data/foods.ts').read_text()
    names = set(re.findall(r"name: '([^']+)'", src))
    for group in re.findall(r"aliases: \[([^\]]*)\]", src):
        names |= set(re.findall(r"'([^']+)'", group))
    return {n.lower() for n in names}


def main():
    df = pd.read_excel(INDB)
    curated = curated_names()
    foods, rejected = [], {}
    for _, r in df.iterrows():
        reason = rejection_reason(r)
        name, aliases = split_name(r.food_name)
        if reason is None and name.lower() in curated:
            reason = 'already in our checked list'
        if reason:
            rejected[reason] = rejected.get(reason, 0) + 1
            continue
        food = {
            'id': f'indb_{r.food_code.lower()}',
            'name': name,
            'category': 'More Dishes',
            'serving': f'1 {r.servings_unit}',
            'kcal': round(r.unit_serving_energy_kcal),
            'protein': round(r.unit_serving_protein_g, 1),
            'carbs': round(r.unit_serving_carb_g, 1),
            'fat': round(r.unit_serving_fat_g, 1),
            'approximate': True,
        }
        if aliases:
            food['aliases'] = aliases
        foods.append(food)

    foods.sort(key=lambda f: f['name'].lower())
    body = ',\n'.join('  ' + json.dumps(f, ensure_ascii=False) for f in foods)
    OUT.write_text(
        '// GENERATED by ml/build_indb_foods.py from the Indian Nutrient Databank (INDB). Do not edit by hand.\n'
        '// Source: Vijayakumar A. et al., Curr Dev Nutr 2024. Values are approximate per-serving estimates.\n'
        "import type { Food } from './foods';\n\n"
        f'export const INDB_FOODS: Food[] = [\n{body},\n];\n'
    )
    print(f'Wrote {len(foods)} dishes to {OUT.relative_to(ROOT)}')
    for reason, n in sorted(rejected.items(), key=lambda t: -t[1]):
        print(f'  skipped {n:4d}: {reason}')


if __name__ == '__main__':
    main()
